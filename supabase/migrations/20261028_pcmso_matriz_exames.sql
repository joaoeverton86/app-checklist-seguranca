-- ==============================================================================
-- MIGRAÇÃO: MATRIZ DE EXAMES DO PCMSO EDITÁVEL PELO PAINEL
-- Antes desta tabela, a matriz de exames por GHE (PCMSO_EXAMES_POR_GHE) era
-- hardcoded em dashboard.js / modules/saude_psicossocial.js: incluir ou remover um
-- exame exigia alterar código e publicar versão nova. Agora o painel lê a matriz
-- daqui e o usuário edita pela tela "🧩 Matriz de Exames" (duas abas: por GHE e
-- por exame).
--
-- Regra de funcionamento no front-end (saude_psicossocial.js):
--   * tabela com pelo menos 1 linha  -> o BANCO é a matriz oficial;
--   * tabela vazia ou inexistente    -> vale a matriz do código (fallback).
-- Por isso o seed abaixo replica exatamente a matriz vigente no v227: rodar a
-- migração não muda nenhuma pendência. A partir daí, só a tela manda.
--
-- Remoção de exame NÃO apaga a linha: marca ativo = false (histórico preservado e
-- o app não precisa de permissão de DELETE).
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.pcmso_matriz_exames (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ghe TEXT NOT NULL,                                  -- '01'..'27'
    exame_id TEXT NOT NULL,                             -- 'clinico' | 'audiometria' | 'acuidade' | ...
    exame_nome TEXT NOT NULL,                           -- como aparece na matriz/relatórios
    periodicidade_meses INTEGER,                        -- NULL = sem periodicidade definida
    demissional BOOLEAN NOT NULL DEFAULT true,          -- também exigido no exame demissional
    ativo BOOLEAN NOT NULL DEFAULT true,                -- false = exame removido do GHE
    ordem INTEGER NOT NULL DEFAULT 0,                   -- ordem de exibição dentro do GHE
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Um exame por GHE. É essa constraint que permite upsert (ghe, exame_id).
CREATE UNIQUE INDEX IF NOT EXISTS uq_pcmso_matriz_ghe_exame
    ON public.pcmso_matriz_exames (ghe, exame_id);
CREATE INDEX IF NOT EXISTS idx_pcmso_matriz_exame
    ON public.pcmso_matriz_exames (exame_id, ativo);

ALTER TABLE public.pcmso_matriz_exames ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Acesso total pcmso_matriz_exames" ON public.pcmso_matriz_exames;
CREATE POLICY "Acesso total pcmso_matriz_exames" ON public.pcmso_matriz_exames
    FOR ALL
    USING (true)
    WITH CHECK (true);

GRANT ALL ON public.pcmso_matriz_exames TO anon, authenticated;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated;

